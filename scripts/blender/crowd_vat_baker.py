"""
Vertex Animation Texture (VAT) Baker & Shader Generator for gkk_flutter / Blender Pipeline.
Author: Ajan-Blender 8 (Armature & Animation Optimization Specialist)

Bakes character skeletal/vertex animation into high-performance 2D textures:
- Encodes animated 3D vertex positions and normal vectors into 2D texture maps (X=vertex ID, Y=frame).
- Computes global animated bounding box, scale, and offset for precise [0, 1] normalization.
- Generates JSON metadata with clip bounds, frame counts, and unpack parameters.
- Generates production-ready GLSL crowd vertex shader with GPU instancing support (1 draw call for 10,000 units).
- Supports both Blender depsgraph evaluation (via `bpy`) and standalone buffer baking (via PIL/NumPy).
"""

from dataclasses import dataclass, field
import json
import math
import os
from typing import Any, Dict, List, Optional, Tuple

import numpy as np
from PIL import Image


@dataclass
class VATClipInfo:
    name: str
    start_frame: int
    end_frame: int
    fps: float
    loop: bool = True


@dataclass
class VATBakeResult:
    vertex_count: int
    total_frames: int
    texture_width: int
    texture_height: int
    bbox_min: Tuple[float, float, float]
    bbox_max: Tuple[float, float, float]
    scale: Tuple[float, float, float]
    offset: Tuple[float, float, float]
    pos_texture_path: str
    norm_texture_path: str
    metadata_path: str
    glsl_shader_path: str


class CrowdVATBaker:
    """Bakes deformed meshes across animation frames into VAT textures."""

    def __init__(self, use_16bit: bool = False):
        self.use_16bit = use_16bit

    def generate_glsl_vertex_shader(
        self,
        tex_width: int,
        tex_height: int,
        bbox_min: Tuple[float, float, float],
        scale: Tuple[float, float, float],
    ) -> str:
        """Generate optimized GLSL vertex shader snippet for crowd instancing."""
        return f"""// =============================================================================
// Crowd Vertex Animation Texture (VAT) Unpack Shader
// Target: 10,000 crowd instances in 1 single draw call (Flutter / WebGL / Vulkan)
// Generated by CrowdVATBaker (Ajan-Blender 8)
// =============================================================================
#version 300 es
precision highp float;

// Base Mesh Vertex Attributes
layout(location = 0) in vec3 aStaticPosition;
layout(location = 1) in vec3 aStaticNormal;
layout(location = 2) in vec2 aTexCoords;
layout(location = 3) in float aVertexID; // Vertex index [0 .. {tex_width - 1}]

// Per-Instance Attributes (GPU Instancing Buffer)
layout(location = 4) in mat4 aInstanceModelMatrix;
layout(location = 8) in vec4 aInstanceAnimData; // x: currentFrame, y: totalFrames, z: animStartFrame, w: animEndFrame

// Uniforms
uniform sampler2D uPosMap;   // VAT Position Texture ({tex_width} x {tex_height})
uniform sampler2D uNormMap;  // VAT Normal Texture ({tex_width} x {tex_height})
uniform mat4 uViewProjection;

// Varyings to Fragment Shader
out vec2 vTexCoords;
out vec3 vWorldNormal;
out vec3 vWorldPos;

const vec3 VAT_OFFSET = vec3({bbox_min[0]:.6f}, {bbox_min[1]:.6f}, {bbox_min[2]:.6f});
const vec3 VAT_SCALE  = vec3({scale[0]:.6f}, {scale[1]:.6f}, {scale[2]:.6f});
const float TEX_WIDTH = {float(tex_width):.1f};
const float TEX_HEIGHT = {float(tex_height):.1f};

void main() {{
    vTexCoords = aTexCoords;

    // Calculate normalized texture coordinate (center of pixel)
    float u = (aVertexID + 0.5) / TEX_WIDTH;
    float currentFrame = aInstanceAnimData.x;
    float v = (currentFrame + 0.5) / TEX_HEIGHT;
    vec2 vatUV = vec2(u, v);

    // Fetch and unpack animated vertex position
    vec3 normalizedPos = texture(uPosMap, vatUV).xyz;
    vec3 localPos = normalizedPos * VAT_SCALE + VAT_OFFSET;

    // Fetch and unpack animated vertex normal
    vec3 normalizedNorm = texture(uNormMap, vatUV).xyz;
    vec3 localNorm = normalize(normalizedNorm * 2.0 - 1.0);

    // Transform to world space via per-instance matrix
    vec4 worldPosition = aInstanceModelMatrix * vec4(localPos, 1.0);
    vWorldPos = worldPosition.xyz;

    // Transform normal using upper 3x3 of instance matrix
    mat3 normalMatrix = mat3(aInstanceModelMatrix);
    vWorldNormal = normalize(normalMatrix * localNorm);

    // Project to clip space
    gl_Position = uViewProjection * worldPosition;
}}
"""

    def bake_frames(
        self,
        positions_by_frame: List[np.ndarray],  # List of (N, 3) arrays
        normals_by_frame: List[np.ndarray],    # List of (N, 3) arrays
        output_dir: str,
        base_name: str = "crowd_char",
        fps: float = 30.0,
        clips: Optional[List[VATClipInfo]] = None,
    ) -> VATBakeResult:
        """
        Bake raw vertex animation frames into VAT images and metadata.
        positions_by_frame: List of length F, each element (N, 3) float positions.
        normals_by_frame: List of length F, each element (N, 3) float normals.
        """
        os.makedirs(output_dir, exist_ok=True)
        total_frames = len(positions_by_frame)
        if total_frames == 0:
            raise ValueError("positions_by_frame must have at least 1 frame.")

        vertex_count = positions_by_frame[0].shape[0]
        for f_idx, (p_arr, n_arr) in enumerate(zip(positions_by_frame, normals_by_frame)):
            if p_arr.shape != (vertex_count, 3):
                raise ValueError(f"Frame {f_idx} positions shape {p_arr.shape} != ({vertex_count}, 3)")
            if n_arr.shape != (vertex_count, 3):
                raise ValueError(f"Frame {f_idx} normals shape {n_arr.shape} != ({vertex_count}, 3)")

        all_pos = np.stack(positions_by_frame, axis=0)  # Shape (F, N, 3)
        all_norm = np.stack(normals_by_frame, axis=0)   # Shape (F, N, 3)

        # 1. Compute global bounding box
        bbox_min = np.min(all_pos, axis=(0, 1))
        bbox_max = np.max(all_pos, axis=(0, 1))
        scale = bbox_max - bbox_min
        # Prevent division by zero for planar/zero bounds
        scale = np.where(scale < 1e-6, 1.0, scale)

        # 2. Normalize positions to [0.0, 1.0]
        norm_pos = (all_pos - bbox_min) / scale
        norm_pos = np.clip(norm_pos, 0.0, 1.0)

        # 3. Normalize normals to [0.0, 1.0]: N * 0.5 + 0.5
        norm_norms = np.linalg.norm(all_norm, axis=-1, keepdims=True)
        norm_norms = np.where(norm_norms < 1e-9, 1.0, norm_norms)
        unit_normals = all_norm / norm_norms
        norm_norm_img = unit_normals * 0.5 + 0.5
        norm_norm_img = np.clip(norm_norm_img, 0.0, 1.0)

        # 4. Construct Image buffers (Width = vertex_count, Height = total_frames)
        # PIL expects array shape (Height, Width, Channels) -> (F, N, 3)
        pos_uint8 = (norm_pos * 255.0).astype(np.uint8)
        norm_uint8 = (norm_norm_img * 255.0).astype(np.uint8)

        pos_img = Image.fromarray(pos_uint8, mode="RGB")
        norm_img = Image.fromarray(norm_uint8, mode="RGB")

        pos_path = os.path.join(output_dir, f"{base_name}_vat_pos.png")
        norm_path = os.path.join(output_dir, f"{base_name}_vat_norm.png")
        pos_img.save(pos_path)
        norm_img.save(norm_path)

        # 5. Metadata JSON
        clip_data = []
        if clips:
            for c in clips:
                clip_data.append({
                    "name": c.name,
                    "start_frame": c.start_frame,
                    "end_frame": c.end_frame,
                    "frame_count": c.end_frame - c.start_frame + 1,
                    "fps": c.fps,
                    "loop": c.loop,
                })
        else:
            clip_data.append({
                "name": "default",
                "start_frame": 0,
                "end_frame": total_frames - 1,
                "frame_count": total_frames,
                "fps": fps,
                "loop": True,
            })

        metadata = {
            "version": "1.0.0",
            "model_name": base_name,
            "vertex_count": vertex_count,
            "total_frames": total_frames,
            "fps": fps,
            "duration_seconds": total_frames / fps,
            "texture_dimensions": {"width": vertex_count, "height": total_frames},
            "bounding_box": {
                "min": bbox_min.tolist(),
                "max": bbox_max.tolist(),
                "scale": scale.tolist(),
                "offset": bbox_min.tolist(),
            },
            "clips": clip_data,
            "textures": {
                "position_map": os.path.basename(pos_path),
                "normal_map": os.path.basename(norm_path),
            },
        }

        meta_path = os.path.join(output_dir, f"{base_name}_vat_meta.json")
        with open(meta_path, "w", encoding="utf-8") as f:
            json.dump(metadata, f, indent=2)

        # 6. GLSL Shader
        glsl_code = self.generate_glsl_vertex_shader(
            tex_width=vertex_count,
            tex_height=total_frames,
            bbox_min=tuple(bbox_min),
            scale=tuple(scale),
        )
        glsl_path = os.path.join(output_dir, f"{base_name}_vat.vert")
        with open(glsl_path, "w", encoding="utf-8") as f:
            f.write(glsl_code)

        return VATBakeResult(
            vertex_count=vertex_count,
            total_frames=total_frames,
            texture_width=vertex_count,
            texture_height=total_frames,
            bbox_min=tuple(bbox_min),
            bbox_max=tuple(bbox_max),
            scale=tuple(scale),
            offset=tuple(bbox_min),
            pos_texture_path=pos_path,
            norm_texture_path=norm_path,
            metadata_path=meta_path,
            glsl_shader_path=glsl_path,
        )

    def bake_blender_action_vat(
        self,
        armature_obj_name: str,
        mesh_obj_name: str,
        action_names: List[str],
        output_dir: str,
        base_name: str = "crowd_mesh",
        fps: float = 30.0,
    ) -> VATBakeResult:
        """
        Bake animation clips directly from Blender scene into VAT textures.
        Evaluates depsgraph frame by frame.
        """
        try:
            import bpy  # type: ignore
        except ImportError:
            raise RuntimeError("bake_blender_action_vat requires Blender environment.")

        arm_obj = bpy.data.objects.get(armature_obj_name)
        mesh_obj = bpy.data.objects.get(mesh_obj_name)
        if not arm_obj or not mesh_obj:
            raise ValueError("Armature or Mesh object not found in Blender scene.")

        positions_by_frame: List[np.ndarray] = []
        normals_by_frame: List[np.ndarray] = []
        clips: List[VATClipInfo] = []

        scene = bpy.context.scene
        depsgraph = bpy.context.evaluated_depsgraph_get()

        curr_frame_cursor = 0
        for act_name in action_names:
            action = bpy.data.actions.get(act_name)
            if not action:
                continue
            if not arm_obj.animation_data:
                arm_obj.animation_data_create()
            arm_obj.animation_data.action = action

            start_f = int(action.frame_range[0])
            end_f = int(action.frame_range[1])
            clip_frames = end_f - start_f + 1

            clips.append(
                VATClipInfo(
                    name=act_name,
                    start_frame=curr_frame_cursor,
                    end_frame=curr_frame_cursor + clip_frames - 1,
                    fps=fps,
                    loop=True,
                )
            )

            for f in range(start_f, end_f + 1):
                scene.frame_set(f)
                depsgraph.update()
                eval_mesh_obj = mesh_obj.evaluated_get(depsgraph)
                eval_mesh = eval_mesh_obj.to_mesh()

                n_verts = len(eval_mesh.vertices)
                pos = np.zeros((n_verts, 3), dtype=np.float32)
                norm = np.zeros((n_verts, 3), dtype=np.float32)

                for idx, v in enumerate(eval_mesh.vertices):
                    pos[idx] = v.co
                    norm[idx] = v.normal

                positions_by_frame.append(pos)
                normals_by_frame.append(norm)
                eval_mesh_obj.to_mesh_clear()
                curr_frame_cursor += 1

        return self.bake_frames(
            positions_by_frame=positions_by_frame,
            normals_by_frame=normals_by_frame,
            output_dir=output_dir,
            base_name=base_name,
            fps=fps,
            clips=clips,
        )
