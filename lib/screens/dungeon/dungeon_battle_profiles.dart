import 'package:flutter/material.dart';

/// Ornamental HUD frame geometry archetype — each renders a distinct custom
/// border silhouette, corner filigree, and header emblem in [DungeonOrnamentalPanel].
enum DungeonHudFrameStyle {
  /// Mossy stone & beast-fang corner notches (forest hunts).
  feralFang,

  /// Twisted ancient roots & glowing bioluminescent spore nodes (swamp/fungal/witch).
  organicSpore,

  /// Faceted hexagonal crystal bevels & prism joints (crystal/glacial/lake).
  crystallineRunic,

  /// Riveted dark-iron octagonal plates & forge notches (mines/dwarves/titans).
  dwarvenForge,

  /// Stepped pyramid corners & golden Pharaonic cartouche lines (desert/tomb/djinn).
  solarHieroglyph,

  /// Sharp lightning chevrons & jagged wind-spear corners (storm mountain peaks).
  tempestGlacier,

  /// Obsidian horn spikes & blood-iron gothic arches (underworld/necropolis/demons).
  infernalSpike,

  /// Double-halo astral arches & starlight diamond filigree (shattered sky & mythic void).
  celestialMythic,
}

/// Real-time Canvas atmospheric & combat weather particle modes.
enum DungeonWeatherVfxType {
  mistClaws,
  venomWebs,
  campEmbers,
  sporeFloat,
  fallingLeaves,
  cursedHexes,
  crystalGlint,
  abyssRipples,
  batSwarm,
  sandstorm,
  solarHieroglyphs,
  blizzard,
  lightningStorm,
  magmaAsh,
  necroticBlood,
  cosmicFracture,
}

/// Visual weapon/magic impact style when the dungeon guardian counter-attacks.
enum DungeonSlashType {
  savageClaw,
  venomSplash,
  heavyCleave,
  elementalBolt,
  necroticScythe,
  cosmicRift,
}

/// Complete bespoke visual, creature, atmospheric, and narrative identity for
/// one specific dungeon (`dng_001` .. `dng_065`).
class DungeonBattleProfile {
  const DungeonBattleProfile({
    required this.dungeonNumber,
    required this.turkishTitle,
    required this.latinTitle,
    required this.zone,
    required this.arenaAsset,
    required this.enemyName,
    required this.enemyTitle,
    required this.enemyElementLabel,
    required this.enemySpriteAsset,
    required this.hudFrameStyle,
    required this.weatherVfx,
    required this.slashStyle,
    required this.primaryColor,
    required this.secondaryColor,
    required this.introQuote,
    required this.clashLines,
    this.isBoss = false,
    this.enemyScale = 1.0,
    this.enemyHover = false,
    this.enemyColorTint,
    this.enemyTintStrength = 0.0,
  });

  final int dungeonNumber;
  final String turkishTitle;
  final String latinTitle;
  final int zone;

  /// Wide 16:9 2.5D interior combat stage asset.
  final String arenaAsset;

  /// Unique lore name of this dungeon's guardian or boss.
  final String enemyName;

  /// Subtitle / epithet displayed beneath the enemy nameplate.
  final String enemyTitle;

  /// Short damage/element tag (e.g. 'KANAMA', 'ZEHİR', 'YILDIRIM', 'HİÇLİK').
  final String enemyElementLabel;

  /// Transparent full-body dark-fantasy creature cutout (`assets/dungeon/mob_*.png`).
  final String enemySpriteAsset;

  final DungeonHudFrameStyle hudFrameStyle;
  final DungeonWeatherVfxType weatherVfx;
  final DungeonSlashType slashStyle;

  /// Primary vibrant accent color (high contrast on dark surfaces).
  final Color primaryColor;

  /// Secondary glow / trim color.
  final Color secondaryColor;

  /// Pre-combat atmospheric quote unique to this dungeon.
  final String introQuote;

  /// Dungeon-specific live combat exchange lines.
  final List<String> clashLines;

  final bool isBoss;
  final double enemyScale;
  final bool enemyHover;
  final Color? enemyColorTint;
  final double enemyTintStrength;

  String get dungeonId => 'dng_${dungeonNumber.toString().padLeft(3, '0')}';

  /// Each dungeon's own portal/shrine monument (`dungeon1.png` or `dungeonN.jpeg`).
  String get portalMonumentAsset => dungeonNumber == 1
      ? 'assets/dungeon/dungeon1.png'
      : 'assets/dungeon/dungeon$dungeonNumber.jpeg';

  Color get deepSurface =>
      Color.lerp(const Color(0xFF070A12), primaryColor, 0.10)!;

  Color get floorRuneColor =>
      Color.lerp(primaryColor, secondaryColor, 0.45)!;

  /// Resolves the exact bespoke profile for any `dng_NNN` ID or dungeon number (1..65).
  static DungeonBattleProfile forDungeonId(
    String dungeonId, {
    int? fallbackZone,
  }) {
    final RegExpMatch? match = RegExp(r'(\d+)').firstMatch(dungeonId);
    final int parsed = match != null ? (int.tryParse(match.group(1)!) ?? 1) : 1;
    return forNumber(parsed, fallbackZone: fallbackZone);
  }

  static DungeonBattleProfile forNumber(
    int number, {
    int? fallbackZone,
  }) {
    final int clamped = number.clamp(1, kAllDungeonBattleProfiles.length);
    return kAllDungeonBattleProfiles[clamped - 1];
  }
}

